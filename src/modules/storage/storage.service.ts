export interface PutOptions {
  contentType: string;
}

export interface DownloadUrlOptions {
  /** Link lifetime. Providers cap it; default comes from configuration. */
  expiresInSeconds?: number;
  /** Suggested name for the browser's save dialog. */
  fileName?: string;
  contentType?: string;
  disposition?: 'attachment' | 'inline';
}

export interface SignedDownload {
  url: string;
  expiresAt: Date;
}

/**
 * Storage port. Business modules depend only on this class and never on the
 * filesystem or an SDK. Buckets/directories are private: the only way to read
 * an object is a short-lived signed URL from `getDownloadUrl`.
 *
 * Planned providers: S3 / Cloudflare R2 / MinIO (presigned GET URLs). `delete`
 * is for purge jobs only; archiving an asset never removes bytes.
 */
export abstract class StorageService {
  abstract readonly providerName: string;
  abstract put(key: string, data: Buffer, options: PutOptions): Promise<void>;
  abstract exists(key: string): Promise<boolean>;
  abstract delete(key: string): Promise<void>;
  abstract getDownloadUrl(
    key: string,
    options?: DownloadUrlOptions,
  ): Promise<SignedDownload>;
}

/** Keys are generated by the server; this rejects anything else, including traversal attempts. */
const KEY_PATTERN =
  /^[a-z0-9][a-z0-9_-]*(\/[a-z0-9][a-z0-9_-]*)*(\.[a-z0-9]{1,8})?$/;

export function assertValidStorageKey(key: string): void {
  if (key.length > 200 || !KEY_PATTERN.test(key)) {
    throw new Error('Invalid storage key');
  }
}
